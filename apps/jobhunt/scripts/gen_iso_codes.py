"""Regenerate the bundled ISO code lists in src/jobhunt/domain/codes/.

Reads Debian's iso-codes JSON (apt package `iso-codes`). Usage, from apps/jobhunt:

    python3 scripts/gen_iso_codes.py [/usr/share/iso-codes/json]
"""

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "jobhunt" / "domain" / "codes"


def load(src: Path, file: str, key: str, field: str) -> list[str]:
    entries = json.loads((src / file).read_text())[key]
    return sorted({e[field] for e in entries if field in e})


def load_country_names(src: Path) -> dict[str, str]:
    """Lowercase ISO name, common name and official name -> alpha-2 code."""
    entries = json.loads((src / "iso_3166-1.json").read_text())["3166-1"]
    return {
        e[field].lower(): e["alpha_2"]
        for e in entries
        for field in ("name", "common_name", "official_name")
        if field in e
    }


def render_names(names: dict[str, str], src: Path) -> str:
    today = datetime.now(UTC).date().isoformat()
    pairs = sorted(names.items())
    rows = (f'    {json.dumps(name, ensure_ascii=False)}: "{code}",' for name, code in pairs)
    body = "\n".join(rows)
    return (
        '"""ISO 3166-1 country names (name, common name, official name), lowercase, to codes.\n\n'
        f"Generated by scripts/gen_iso_codes.py from {src} on {today}.\n"
        f'{len(names)} names. Do not edit by hand.\n"""\n\n'
        f"COUNTRY_NAMES: dict[str, str] = {{\n{body}\n}}\n"
    )


def render(const: str, doc: str, codes: list[str], per_line: int, src: Path) -> str:
    rows = [" ".join(codes[i : i + per_line]) for i in range(0, len(codes), per_line)]
    body = "\n".join(f'        "{row} "' for row in rows)
    today = datetime.now(UTC).date().isoformat()
    return (
        f'"""{doc}\n\n'
        f"Generated by scripts/gen_iso_codes.py from {src} on {today}.\n"
        f'{len(codes)} codes. Do not edit by hand.\n"""\n\n'
        f"{const}: frozenset[str] = frozenset(\n    (\n{body}\n    ).split()\n)\n"
    )


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/iso-codes/json")
    lists = [
        ("countries.py", "COUNTRY_CODES", "ISO 3166-1 alpha-2 country codes.",
         load(src, "iso_3166-1.json", "3166-1", "alpha_2"), 20),
        ("currencies.py", "CURRENCY_CODES", "ISO 4217 currency codes.",
         load(src, "iso_4217.json", "4217", "alpha_3"), 16),
        ("languages.py", "LANGUAGE_CODES", "ISO 639-1 language codes.",
         load(src, "iso_639-2.json", "639-2", "alpha_2"), 20),
    ]  # fmt: skip
    for file, const, doc, codes, per_line in lists:
        (OUT / file).write_text(render(const, doc, codes, per_line, src))
    (OUT / "country_names.py").write_text(render_names(load_country_names(src), src))


if __name__ == "__main__":
    main()
